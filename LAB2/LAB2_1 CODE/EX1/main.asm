/*XTAL is 8MHz, we scale down 64*/
	LDI	R16,(1<<0)		;SET BIT 0
	SBI	DDRA,0			
	LDI	R17,0		
	OUT	PORTA,R17	
	LDI	R20,124			;STORE 124 INTO OCR0A
	OUT	OCR0A,R20		
Delay1ms:	
	LDI	R20,0x02		;SET WGM01 ON
	OUT	TCCR0A,R20 		
	LDI	R20,0x03		;SET CSO1 AND CSO2
	OUT	TCCR0B,R20
AGAIN:	
	SBIS	TIFR0,OCF0A	
	RJMP	AGAIN

	LDI		R20,0x0
	OUT		TCCR0B,R20		
	LDI		R20,1<<OCF0A
	OUT		TIFR0,R20
				
	EOR		R17,R16			
	OUT		PORTA,R17		
RJMP 	Delay1ms
