/*XTAL is 8MHz, we scale down 64*/
	LDI R20, 0xFF
	OUT OCR0A, R20
	SBI DDRB, 3
DELAY:	
	LDI	R20,0xFC		;
	OUT	TCNT0,R20
	LDI	R20,0x40		;SET WGM01 ON
	OUT	TCCR0A,R20 		
	LDI	R20,0x03		;SET CSO1 AND CSO2
	OUT	TCCR0B,R20
AGAIN:	
	SBIS	TIFR0,TOV0	
	RJMP	AGAIN

	LDI		R20,0x0
	OUT		TCCR0B,R20		
	LDI		R20,1<<TOV0
	OUT		TIFR0,R20
	RJMP 	DELAY
